// Reproducible Unicode 17.0.0 table generation; no network access.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const root = new URL('../', import.meta.url);
const hashes = {
  'GraphemeBreakProperty.txt':'d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89',
  'emoji-data.txt':'2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b',
  'DerivedCoreProperties.txt':'24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08',
  'GraphemeBreakTest.txt':'e2d134d2c52919bace503ebb6a551c1855fe1a1faec18478c78fff254a1793ec'
};
const read = name => {
  const bytes = readFileSync(new URL('Tests/Unicode/' + name, root));
  if (createHash('sha256').update(bytes).digest('hex') !== hashes[name])
    throw new Error('Unicode source checksum mismatch: ' + name);
  return bytes.toString('utf8');
};
const names = ['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT'];
function ranges(file, select) {
  const result = [];
  for (const line of read(file).split('\n')) {
    const parts = line.split('#')[0].trim().split(';').map(x => x.trim());
    if (!parts[0]) continue;
    const value = select(parts);
    if (value === undefined) continue;
    const [lo, hi = lo] = parts[0].split('..').map(x => parseInt(x, 16));
    if (![lo, hi, value].every(Number.isInteger)) throw new Error('Invalid data: ' + line);
    result.push([lo,hi,value]);
  }
  return result.sort((a,b) => a[0]-b[0]);
}
const tables = [
  ['GraphemeProperties', ranges('GraphemeBreakProperty.txt', p => {
    const n = names.indexOf(p[1]); if (n < 0) throw new Error(p[1]); return n;
  })],
  ['PictographicProperties', ranges('emoji-data.txt', p => p[1] === 'Extended_Pictographic' ? 1 : undefined)],
  ['IndicProperties', ranges('DerivedCoreProperties.txt', p => p[1] === 'InCB' ? {Consonant:1,Extend:2,Linker:3}[p[2]] : undefined)]
];
let output = '// Generated by Tools/generate-grapheme-data.mjs; Unicode 17.0.0.\n// See Tests/Unicode/LICENSE.txt. Do not edit manually.\n';
for (const [name, values] of tables) {
  if (!values.length) throw new Error('Empty ' + name);
  for (let i=1;i<values.length;i++) if (values[i][0] <= values[i-1][1]) throw new Error('Overlapping ranges');
  output += `const ${name}: array[0..${values.length-1}] of TUnicodeRange = (\n`;
  output += values.map(([lo,hi,v])=>`  (FLo:$${lo.toString(16)}; FHi:$${hi.toString(16)}; FValue:${v})`).join(',\n') + '\n);\n';
}
writeFileSync(new URL('Source/PasSDL3.GUI.Grapheme.Data.inc', root), output);
let tests = '// Generated from Unicode 17.0.0 GraphemeBreakTest.txt.\n';
let count = 0;
for (const line of read('GraphemeBreakTest.txt').split('\n')) {
  const data = line.split('#')[0].trim(); if (!data) continue;
  const cp = [], boundaries = [];
  for (const token of data.split(/\s+/)) {
    if (token === '÷') boundaries.push(cp.length);
    else if (token !== '×') cp.push('$' + token);
  }
  tests += `CheckCase([${cp.join(',')}], [${boundaries.join(',')}]);\n`; count++;
}
if (count < 500) throw new Error('Incomplete conformance fixture');
writeFileSync(new URL('Tests/Unicode/GraphemeCases.inc', root), tests);
console.log(`Generated ${count} conformance cases and ${tables.map(t=>t[1].length).join('/')} property ranges.`);
